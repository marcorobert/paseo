const fs = require("node:fs");
const path = require("node:path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by with-android-trust-user-cas. Opt-in only, for devices whose platform CA
  store predates the roots a server presents (e.g. Android 7.0 and Let's Encrypt's
  X1/X2 hierarchy). Trusting "user" alongside "system" lets a manually installed CA
  anchor those chains. It also means any CA installed on the device is trusted by this
  app, which is why it is gated behind PASEO_ANDROID_TRUST_USER_CAS.
-->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
      <certificates src="user" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function withAndroidTrustUserCas(config) {
  config = withDangerousMod(config, [
    "android",
    (modConfig) => {
      const resDir = path.join(
        modConfig.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "res",
        "xml",
      );
      fs.mkdirSync(resDir, { recursive: true });
      fs.writeFileSync(path.join(resDir, "network_security_config.xml"), NETWORK_SECURITY_CONFIG);
      return modConfig;
    },
  ]);

  return withAndroidManifest(config, (modConfig) => {
    const application = modConfig.modResults.manifest.application?.[0];
    if (application) {
      application.$["android:networkSecurityConfig"] = "@xml/network_security_config";
    }
    return modConfig;
  });
}

module.exports = withAndroidTrustUserCas;
